def scratch_var(prefix, scratch_name, segment_name, field):
    return (
        f"{prefix}_scratch_{c_identifier(scratch_name)}_"
        f"{c_identifier(segment_name)}_{field}"
    )


def emit_scratch_plans(lines, route, context, route_constant):
    scratch = route_schema.validate_scratch(route, "route", context)
    segment_layout = {}
    for scratch_name, scratch_class in scratch.items():
        scratch_index = scratch_class["index"]
        previous_end = "0"
        for segment in scratch_class["segments"]:
            segment_name = segment["name"]
            value_var = scratch_var("route", scratch_name, segment_name, "length_value")
            length_var = scratch_var("route", scratch_name, segment_name, "length")
            offset_var = scratch_var("route", scratch_name, segment_name, "offset")
            end_var = scratch_var("route", scratch_name, segment_name, "end")
            length_expr = emit_integer_operand(segment["length"], context)
            alignment = segment["alignment"]
            lines.extend([
                f"    const int64_t {value_var} = static_cast<int64_t>({length_expr});",
                f"    if ({value_var} <= 0) {{",
                f"        {failed_response(route_constant)}",
                "    }",
                f"    const size_t {length_var} = static_cast<size_t>({value_var});",
                f"    if ({previous_end} > SIZE_MAX - {alignment - 1}) {{",
                f"        {failed_response(route_constant)}",
                "    }",
                f"    const size_t {offset_var} = "
                f"({previous_end} + {alignment - 1}) / {alignment} * {alignment};",
                f"    if ({length_var} > SIZE_MAX - {offset_var}) {{",
                f"        {failed_response(route_constant)}",
                "    }",
                f"    const size_t {end_var} = {offset_var} + {length_var};",
            ])
            segment_layout[f"{scratch_name}.{segment_name}"] = {
                "scratch_index": scratch_index,
                "offset": offset_var,
                "length": length_var,
            }
            previous_end = end_var
        lines.extend([
            f"    plan->scratch[{scratch_index}].name = {cpp_string(scratch_name)};",
            f"    plan->scratch[{scratch_index}].bytes = {previous_end};",
            f"    plan->scratch[{scratch_index}].minimum_capacity = "
            f"{scratch_class['minimum_capacity']};",
        ])
    lines.append(f"    plan->scratch_count = {len(scratch)};")
    return scratch, segment_layout


def emit_dispatch_plan(
        lines,
        dispatch,
        context,
        plan_expr,
        entry_expr,
        prefix,
        route_constant):
    if "work_items" in dispatch:
        helper = "ggml_backend_hrx_make_work_items_dispatch_config"
        values = route_schema.require_array(dispatch, "work_items", "route")
        value_name = f"{prefix}_dispatch_work_items"
    else:
        helper = "ggml_backend_hrx_make_workgroup_dispatch_config"
        values = route_schema.require_array(dispatch, "workgroups", "route")
        value_name = f"{prefix}_dispatch_workgroups"
    x, y, z = route_emit.dispatch_axis_exprs(values, context, route_schema)
    lines.extend([
        f"    const int64_t {value_name}[3] = {{{x}, {y}, {z}}};",
        f"    if (!{helper}({entry_expr}->workgroup_size, {value_name}, "
        f"&{plan_expr}.dispatch)) {{",
        f"        {failed_response(route_constant)}",
        "    }",
    ])


def emit_kernel_plan(
        lines,
        owner,
        definition,
        context,
        plan_expr,
        entry_expr,
        prefix,
        segment_layout,
        route_constant):
    invocation = route_schema.require_dict(owner, "invocation", "route")
    buffers = sorted(route_schema.require_array(invocation, "buffers", "route"), key=lambda item: item["position"])
    scalars = sorted(route_schema.require_array(invocation, "scalars", "route"), key=lambda item: item["position"])
    dispatch = route_schema.require_dict(invocation, "dispatch", "route")
    abi = route_schema.require_dict(definition, "abi", "definition")
    constant_byte_length = route_schema.require_int(abi, "constant_byte_length", "definition")
    offsets, constants_size = scalar_offsets(scalars, "route")
    if constants_size != constant_byte_length:
        raise ValueError(f"route scalar size {constants_size} does not match definition constant bytes {constant_byte_length}")

    lines.append(f"    {plan_expr}.entry = {entry_expr};")
    emit_config_materialization(lines, owner, prefix)
    emit_config_plan_copy(lines, owner, plan_expr, prefix)

    for buffer in buffers:
        position = route_schema.require_int(buffer, "position", "route")
        if "tensor" in buffer:
            tensor = route_schema.require_string(buffer, "tensor", "route")
            lines.append(BIND_BUFFER_TEMPLATE.format(
                plan_expr=plan_expr,
                tensor=route_emit.role_var(tensor),
                position=position,
                route_id_constant=route_constant,
            ))
        else:
            reference = route_schema.require_string(buffer, "scratch", "route")
            layout = segment_layout[reference]
            lines.extend([
                f"    {plan_expr}.binding_scratch_index[{position}] = "
                f"{layout['scratch_index'] + 1};",
                f"    {plan_expr}.binding_scratch_offset[{position}] = "
                f"{layout['offset']};",
                f"    {plan_expr}.binding_scratch_length[{position}] = "
                f"{layout['length']};",
            ])
    lines.append(f"    {plan_expr}.binding_count = {len(buffers)};")

    for scalar, offset in zip(scalars, offsets):
        name = route_schema.require_string(scalar, "name", "route")
        scalar_type = route_schema.require_string(scalar, "type", "route")
        cpp_type = CPP_SCALAR_TYPES[scalar_type]
        if "source" in scalar:
            value = typed_expr(source_expr(route_schema.require_string(scalar, "source", "route")), scalar_type)
        else:
            value = scalar_literal(scalar["value"], scalar_type)
        temp = f"{prefix}_constant_{c_identifier(name)}"
        lines.append(PACK_SCALAR_TEMPLATE.format(
            cpp_type=cpp_type,
            name=temp,
            value=value,
            offset=offset,
            plan_expr=plan_expr,
        ))
    lines.append(f"    {plan_expr}.constants_size = {constant_byte_length};")

    emit_dispatch_plan(
        lines,
        dispatch,
        context,
        plan_expr,
        entry_expr,
        prefix,
        route_constant,
    )


def load_prepass_definitions(route_path, route):
    result = []
    for i, prepass in enumerate(route.get("prepasses", [])):
        source = f"{route_path}: prepasses[{i}]"
        definition_path = (
            route_path.parent /
            route_schema.require_string(prepass, "definition", source)
        ).resolve()
        result.append((prepass, definition_path, route_schema.read_json(definition_path)))
    return result


def emit_prepass_entry_lookups(lines, prepasses):
    for i, (prepass, _, _) in enumerate(prepasses):
        prepass_id = route_schema.require_string(
            prepass,
            "id",
            f"route: prepasses[{i}]",
        )
        lines.extend([
            f"    const ggml_backend_hrx_loom_catalog_entry * prepass_entry_{i} =",
            f"        ggml_backend_hrx_loom_find_entry(catalog, {cpp_string(prepass_id)});",
            f"    if (!prepass_entry_{i}) {{",
            "        return ggml_backend_hrx_loom_unsupported("
            "GGML_BACKEND_HRX_LOOM_UNSUPPORTED_TARGET);",
            "    }",
        ])


def emit_plan_setup(lines, route_constant, consumed_node_indices):
    if len(consumed_node_indices) > 8:
        raise ValueError(f"route consumes too many graph nodes: {len(consumed_node_indices)}")
    lines.append(PLAN_SETUP_TEMPLATE.format(route_id_constant=route_constant))
    lines.append(f"    plan->consumed_node_count = {len(consumed_node_indices)};")
    for i, node_index in enumerate(consumed_node_indices):
        lines.append(f"    plan->consumed_node_indices[{i}] = {node_index};")


def emit_execution_plan(
        lines,
        route,
        definition,
        context,
        prepasses,
        route_constant,
        consumed_node_indices):
    emit_plan_setup(lines, route_constant, consumed_node_indices)
    scratch, segment_layout = emit_scratch_plans(
        lines,
        route,
        context,
        route_constant,
    )
    emit_kernel_plan(
        lines,
        route,
        definition,
        context,
        "plan->main",
        "entry",
        "main",
        segment_layout,
        route_constant,
    )
    for i, (prepass, _, prepass_definition) in enumerate(prepasses):
        prepass_plan = f"plan->prepasses[{i}]"
        emit_kernel_plan(
            lines,
            prepass,
            prepass_definition,
            context,
            f"{prepass_plan}.kernel",
            f"prepass_entry_{i}",
            f"prepass_{i}",
            segment_layout,
            route_constant,
        )
        cache = route_schema.require_dict(
            prepass,
            "cache",
            f"route: prepasses[{i}]",
        )
        cache_scratch = route_schema.require_string(cache, "scratch", "route")
        cache_tensor = route_schema.require_string(cache, "tensor", "route")
        region = cache.get("region")
        lines.append(
            f"    {prepass_plan}.cache_scratch_index = "
            f"{scratch[cache_scratch]['index'] + 1};"
        )
        if region is not None:
            offset_expr = emit_integer_operand(region.get("offset", 0), context)
            length_expr = emit_integer_operand(region["length"], context)
            lines.extend([
                f"    const int64_t prepass_{i}_cache_region_offset = "
                f"static_cast<int64_t>({offset_expr});",
                f"    const int64_t prepass_{i}_cache_region_length = "
                f"static_cast<int64_t>({length_expr});",
                f"    if (prepass_{i}_cache_region_offset < 0 || "
                f"prepass_{i}_cache_region_length <= 0 ||",
                f"        static_cast<uint64_t>(prepass_{i}_cache_region_offset) > SIZE_MAX || "
                f"static_cast<uint64_t>(prepass_{i}_cache_region_length) > SIZE_MAX) {{",
                f"        {failed_response(route_constant)}",
                "    }",
                f"    {prepass_plan}.cache_region_offset = "
                f"static_cast<size_t>(prepass_{i}_cache_region_offset);",
                f"    {prepass_plan}.cache_region_length = "
                f"static_cast<size_t>(prepass_{i}_cache_region_length);",
            ])
        lines.extend([
            f"    {prepass_plan}.cache_source = {route_emit.role_var(cache_tensor)};",
            f"    if (!ggml_backend_hrx_loom_bind_tensor(request, "
            f"{route_emit.role_var(cache_tensor)}, &{prepass_plan}.cache_source_binding)) {{",
            f"        {failed_response(route_constant)}",
            "    }",
        ])
    lines.append(f"    plan->prepass_count = {len(prepasses)};")


def fusion_op_var(op_name):
    return f"{c_identifier(op_name)}_op"


def fusion_role_expr(op_var, role):
    if role == "dst":
        return op_var
    if role.startswith("src") and role[3:].isdigit():
        return f"{op_var}->src[{int(role[3:])}]"
    raise ValueError(f"unsupported tensor role {role}")


def emit_fusion_op_setup(lines, route, route_constant):
    match = route_schema.require_dict(route, "match", "route")
    ops = route_schema.require_dict(match, "ops", "route")
    op_names = list(ops)
    matched_node_count = len(op_names)
    lines.extend([
        f"    static constexpr int matched_node_count = {matched_node_count};",
        "    if (!request->cgraph || request->node_index < 0 ||",
        "            request->node_index + matched_node_count > request->cgraph->n_nodes ||",
        "            request->cgraph->nodes[request->node_index] != node) {",
        "        return ggml_backend_hrx_loom_unsupported(GGML_BACKEND_HRX_LOOM_UNSUPPORTED_NO_ROUTE);",
        "    }",
    ])
    for i, op_name in enumerate(op_names):
        op_match = route_schema.require_dict(ops[op_name], "tensors", "route")
        del op_match
        op = route_schema.require_string(ops[op_name], "op", "route")
        op_var = fusion_op_var(op_name)
        source = "node" if i == 0 else f"request->cgraph->nodes[request->node_index + {i}]"
        lines.extend([
            f"    const ggml_tensor * {op_var} = {source};",
            f"    if (!{op_var} || {op_var}->op != {op}) {{",
            "        return ggml_backend_hrx_loom_unsupported(GGML_BACKEND_HRX_LOOM_UNSUPPORTED_NO_ROUTE);",
            "    }",
        ])

    assigned = {}
    for op_name, op_match in ops.items():
        op_var = fusion_op_var(op_name)
        op_tensors = route_schema.require_dict(op_match, "tensors", "route")
        for role, tensor_name in op_tensors.items():
            expr = fusion_role_expr(op_var, role)
            tensor_var = route_emit.role_var(tensor_name)
            if tensor_name not in assigned:
                assigned[tensor_name] = expr
                lines.append(f"    const ggml_tensor * {tensor_var} = {expr};")
            else:
                lines.extend([
                    f"    if ({tensor_var} != {expr}) {{",
                    "        return ggml_backend_hrx_loom_unsupported(GGML_BACKEND_HRX_LOOM_UNSUPPORTED_SHAPE);",
                    "    }",
                ])

    tensors = route_schema.route_tensors(route, "route")
    required = sorted(name for name, tensor in tensors.items() if not tensor.get("optional", False))
    if required:
        condition = " || ".join([f"!{route_emit.role_var(name)}" for name in required])
        lines.extend([
            f"    if ({condition}) {{",
            "        return ggml_backend_hrx_loom_unsupported(GGML_BACKEND_HRX_LOOM_UNSUPPORTED_SHAPE);",
            "    }",
        ])


def emit_fusion_attributes(lines, route):
    match = route_schema.require_dict(route, "match", "route")
    ops = route_schema.require_dict(match, "ops", "route")
    for op_name, op_match in ops.items():
        op = route_schema.require_string(op_match, "op", "route")
        attributes = op_match.get("attributes", {})
        if not attributes:
            continue
        indices = ATTRIBUTE_INDICES[op]
        op_var = fusion_op_var(op_name)
        for name, attr in attributes.items():
            scalar_type = route_schema.require_string(attr, "type", "route")
            getter = route_emit.ATTRIBUTE_GETTERS[scalar_type]
            cast = CPP_SCALAR_TYPES[scalar_type]
            lines.append(f"    const {cast} {route_emit.fusion_attribute_var(op_name, name)} = {getter}({op_var}, {indices[name]});")


def generate_fusion_route_impl(route_path, route, definition):
    match = route_schema.require_dict(route, "match", route_path)
    ops = route_schema.require_dict(match, "ops", route_path)
    anchors = match.get("anchors", [])
    anchor_name = anchors[0] if anchors else next(iter(ops))
    anchor_op = route_schema.require_string(ops[anchor_name], "op", route_path)
    route_id = route_schema.require_string(route, "id", route_path)
    function_name = route_function_name(route_id)
    route_constant = route_id_constant(route_id)
    prepasses = load_prepass_definitions(route_path, route)
    context = route_schema.FusionRouteContext(
        route_path,
        route_schema.route_tensors(route, route_path),
        {op_name: op_match.get("attributes", {}) for op_name, op_match in ops.items()},
        route_schema.require_dict(route, "derived", route_path),
    )

    lines = []
    lines.append(ROUTE_FUNCTION_OPEN_TEMPLATE.format(
        function_name=function_name,
        op=anchor_op,
        route_id_constant=route_constant,
    ))
    emit_prepass_entry_lookups(lines, prepasses)
    emit_fusion_op_setup(lines, route, route_constant)
    route_emit.emit_dtype_checks(
        lines,
        route,
        route_schema,
        route_response,
        "GGML_BACKEND_HRX_LOOM_UNSUPPORTED_DTYPE",
    )
    route_emit.emit_storage_checks(
        lines,
        route,
        route_schema,
        route_response,
        "GGML_BACKEND_HRX_LOOM_UNSUPPORTED_LAYOUT",
    )
    emit_fusion_attributes(lines, route)
    route_emit.emit_shape_captures(lines, route, route_schema)
    route_emit.emit_tensor_declaration_checks(
        lines,
        route,
        route_schema,
        route_response,
        "GGML_BACKEND_HRX_LOOM_UNSUPPORTED_SHAPE",
        "GGML_BACKEND_HRX_LOOM_UNSUPPORTED_LAYOUT",
    )
    route_emit.emit_derived(lines, route, context, route_schema, "ggml_backend_hrx_loom_next_power_of_2")
    route_emit.emit_predicates(lines, route, context, route_schema, UNSUPPORTED_REASON_BY_PREDICATE, route_response)
    emit_execution_plan(
        lines,
        route,
        definition,
        context,
        prepasses,
        route_constant,
        [f"request->node_index + {i}" for i in range(len(ops))],
    )
    lines.append(f"    return ggml_backend_hrx_loom_supported({route_constant});")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def generate_route_impl(route_path, route, definition):
    route_emit.validate_attribute_indices(route, route_path, route_schema, ATTRIBUTE_INDICES)
    if route_schema.route_is_fusion_v2(route, route_path):
        return generate_fusion_route_impl(route_path, route, definition)

    match = route_schema.require_dict(route, "match", route_path)
    op = route_schema.require_string(match, "op", f"{route_path}: match")
    op_rule = route_schema.OP_RULES[op]
    route_id = route_schema.require_string(route, "id", route_path)
    function_name = route_function_name(route_id)
    route_constant = route_id_constant(route_id)
    prepasses = load_prepass_definitions(route_path, route)
    context = route_schema.RouteContext(
        route_path,
        op_rule,
        route_schema.route_tensors(route, route_path),
        match.get("attributes", {}),
        route_schema.require_dict(route, "derived", route_path),
    )

    lines = []
    lines.append(ROUTE_FUNCTION_OPEN_TEMPLATE.format(
        function_name=function_name,
        op=op,
        route_id_constant=route_constant,
    ))
    emit_prepass_entry_lookups(lines, prepasses)
    route_emit.emit_tensor_setup(
        lines,
        route,
        op_rule,
        route_schema,
        route_response,
        "GGML_BACKEND_HRX_LOOM_UNSUPPORTED_SHAPE",
    )
    route_emit.emit_dtype_checks(
        lines,
        route,
        route_schema,
        route_response,
        "GGML_BACKEND_HRX_LOOM_UNSUPPORTED_DTYPE",
    )
    route_emit.emit_storage_checks(
        lines,
        route,
        route_schema,
        route_response,
        "GGML_BACKEND_HRX_LOOM_UNSUPPORTED_LAYOUT",
    )
    route_emit.emit_attributes(lines, route, route_schema, ATTRIBUTE_INDICES)
    route_emit.emit_shape_captures(lines, route, route_schema)
    route_emit.emit_tensor_declaration_checks(
        lines,
        route,
        route_schema,
        route_response,
        "GGML_BACKEND_HRX_LOOM_UNSUPPORTED_SHAPE",
        "GGML_BACKEND_HRX_LOOM_UNSUPPORTED_LAYOUT",
    )
    route_emit.emit_derived(lines, route, context, route_schema, "ggml_backend_hrx_loom_next_power_of_2")
    route_emit.emit_predicates(lines, route, context, route_schema, UNSUPPORTED_REASON_BY_PREDICATE, route_response)
    emit_execution_plan(
        lines,
        route,
        definition,
        context,
        prepasses,
        route_constant,
        ["request->node_index"],
    )
    lines.append(f"    return ggml_backend_hrx_loom_supported({route_constant});")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def generate_dispatcher_impl(routes):
    lines = [DISPATCHER_CPP_HEADER_TEMPLATE]
    route_infos = route_emit.route_infos_for_dispatcher(routes, route_schema)
    ops = route_emit.ops_from_route_infos(route_infos)

    for op in ops:
        lines.extend([
            f"ggml_backend_hrx_loom_op_response {op_router_function_name(op)}(",
            "        ggml_backend_hrx_loom_catalog * catalog,",
            "        const ggml_backend_hrx_loom_op_request * request,",
            "        ggml_backend_hrx_loom_execution_plan * plan);",
            "",
        ])

    lines.append(DISPATCHER_FUNCTION_OPEN_TEMPLATE)
    for op in ops:
        lines.extend([
            f"        case {op}:",
            f"            return {op_router_function_name(op)}(catalog, request, plan);",
        ])
    lines.append(DISPATCHER_FUNCTION_CLOSE_TEMPLATE)
    return "\n".join(lines)


def generate_op_router_impl(routes, selected_op):
    lines = [DISPATCHER_CPP_HEADER_TEMPLATE]

    route_infos = route_emit.route_infos_for_op(routes, selected_op, route_schema)
    if not route_infos:
        raise ValueError(f"no routes found for {selected_op}")

    for _, _, route_path, route, definition in route_infos:
        route_id = route_schema.require_string(route, "id", route_path)
        lines.extend([
            f"static constexpr const char * {route_id_constant(route_id)} = {cpp_string(route_id)};",
            "",
            generate_route_impl(route_path, route, definition),
        ])

    function_name = op_router_function_name(selected_op)
    lines.extend([
        f"ggml_backend_hrx_loom_op_response {function_name}(",
        "        ggml_backend_hrx_loom_catalog * catalog,",
        "        const ggml_backend_hrx_loom_op_request * request,",
        "        ggml_backend_hrx_loom_execution_plan * plan);",
        "",
        f"ggml_backend_hrx_loom_op_response {function_name}(",
        "        ggml_backend_hrx_loom_catalog * catalog,",
        "        const ggml_backend_hrx_loom_op_request * request,",
        "        ggml_backend_hrx_loom_execution_plan * plan) {",
        "    ggml_backend_hrx_loom_op_response fallback =",
        "        ggml_backend_hrx_loom_unsupported(GGML_BACKEND_HRX_LOOM_UNSUPPORTED_NO_ROUTE);",
        "",
    ])

    for _, route_id, _, _, _ in route_infos:
        lines.extend([
            "    {",
            "        ggml_backend_hrx_loom_op_response response =",
            f"            {route_function_name(route_id)}(catalog, request, plan);",
            "        if (response.result != GGML_BACKEND_HRX_LOOM_UNSUPPORTED) {",
            "            return response;",
            "        }",
            "        if (fallback.unsupported_reason == GGML_BACKEND_HRX_LOOM_UNSUPPORTED_NO_ROUTE &&",
            "            response.unsupported_reason != GGML_BACKEND_HRX_LOOM_UNSUPPORTED_NO_ROUTE) {",
            "            fallback = response;",
            "        }",
            "    }",
            "",
        ])

    lines.extend([
        "    return fallback;",
        "}",
        "",
    ])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--source-root", default=str(route_validator.default_source_root()))
    parser.add_argument("--route", required=True, action="append")
    parser.add_argument("--out", required=True)
    parser.add_argument("--dispatcher", action="store_true")
    parser.add_argument("--op-router", action="store_true")
    parser.add_argument("--op")
    args = parser.parse_args()

    try:
        routes = [load_route(Path(args.source_root), route_name) for route_name in args.route]
        if args.dispatcher:
            output = generate_dispatcher_impl([(route_path, route, definition) for route_path, route, _, definition in routes])
        elif args.op_router:
            if not args.op:
                raise ValueError("--op-router expects --op")
            output = generate_op_router_impl([(route_path, route, definition) for route_path, route, _, definition in routes], args.op)
        else:
            raise ValueError("expected --dispatcher or --op-router")
        out_path = Path(args.out)
        out_path.parent.mkdir(parents=True, exist_ok=True)
        out_path.write_text(output, encoding="utf-8")
    except (OSError, json.JSONDecodeError, ValueError) as err:
        print(f"ValueError: {err}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
